function quote(value) {
	return `"${String(value).replaceAll('"', '\\"')}"`;
}

function dotNode(id, label, { fill = '#0f172a', color = '#334155', font = '#e2e8f0', shape = 'box' } = {}) {
	return `${id} [label=${quote(label)}, shape=${shape}, style="rounded,filled", fillcolor=${quote(fill)}, color=${quote(color)}, fontcolor=${quote(font)}];`;
}

function writeDot(name, title, body) {
	const dot = `digraph G {
graph [rankdir=LR, bgcolor="#f8fafc", pad="0.4", nodesep="0.55", ranksep="0.75", splines=ortho, outputorder=edgesfirst, label=${quote(title)}, labelloc=t, fontsize=22, fontname="Arial", fontcolor="#0f172a"];
node [fontname="Arial", fontsize=13, margin="0.14,0.1"];
edge [fontname="Arial", fontsize=10, color="#64748b", arrowsize=0.8];
${body}
}`;
	const dotPath = path.join(outDir, `${name}.dot`);
	const svgPath = path.join(outDir, `${name}.svg`);
	fs.writeFileSync(dotPath, dot);
	execFileSync('dot', ['-Tsvg', dotPath, '-o', svgPath]);
	fs.unlinkSync(dotPath);
}

