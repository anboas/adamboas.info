function csvEscape(value) {
	const text = String(value ?? '');
	if (/[",\n\r]/.test(text)) return `"${text.replaceAll('"', '""')}"`;
	return text;
}

function writeCsv(name, header, rows) {
	const normalizedRows = rows.map((row) =>
		Array.isArray(row)
			? row
			: [
					row.id,
					row.opportunity,
					priorityById[row.id] ?? 'P3',
					laneById[row.id] ?? 'Watch',
					row.focus,
					row.customer,
					row.type,
					row.dueDate,
					row.noticeId,
					row.vehicle,
					row.valueTiming,
					row.posture,
					row.fit,
					row.nextAction,
					row.confidence,
					row.sourceUrl,
				],
	);
	fs.writeFileSync(
		path.join(outDir, name),
		[header, ...normalizedRows].map((row) => row.map(csvEscape).join(',')).join('\n'),
	);
}

