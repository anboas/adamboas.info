function csvEscape(value) {
	const text = String(value ?? '');
	return /[",\n\r]/.test(text) ? `"${text.replaceAll('"', '""')}"` : text;
}

function writeCsv(fileName, headers, rows) {
	const text = [headers, ...rows].map((row) => row.map(csvEscape).join(',')).join('\n') + '\n';
	fs.writeFileSync(path.join(outDir, fileName), text);
}

function esc(value) {
	return String(value ?? '')
		.replaceAll('&', '&amp;')
		.replaceAll('<', '&lt;')
		.replaceAll('>', '&gt;');
}

function wrapText(label, width = 24) {
	const words = String(label).split(/\s+/);
	const lines = [];
	let line = '';
	for (const word of words) {
		if (`${line} ${word}`.trim().length > width && line) {
			lines.push(line);
			line = word;
		} else {
			line = `${line} ${word}`.trim();
		}
	}
	if (line) lines.push(line);
	return lines.slice(0, 5);
}

function box(x, y, width, height, title, subtitle, tone = 'node') {
	const lines = wrapText(title, Math.max(16, Math.floor(width / 8)));
	const subLines = subtitle ? wrapText(subtitle, Math.max(18, Math.floor(width / 7.5))).slice(0, 2) : [];
	const titleText = lines
		.map((line, index) => `<text x="${x + 16}" y="${y + 26 + index * 16}" class="box-title">${esc(line)}</text>`)
		.join('');
	const subtitleText = subLines
		.map(
			(line, index) =>
				`<text x="${x + 16}" y="${y + height - 32 + index * 14}" class="box-subtitle">${esc(line)}</text>`,
		)
		.join('');
	return `<g class="box ${tone}"><rect x="${x}" y="${y}" width="${width}" height="${height}" rx="0"/><line x1="${x}" y1="${y}" x2="${x}" y2="${y + height}" class="accent"/><g>${titleText}${subtitleText}</g></g>`;
}

function line(x1, y1, x2, y2, dashed = false) {
	const midX = Math.round((x1 + x2) / 2);
	return `<path d="M ${x1} ${y1} H ${midX} V ${y2} H ${x2}" class="connector${dashed ? ' dashed' : ''}"/>`;
}

function branch(x1, y1, x2, y2, busY, dashed = false) {
	return `<path d="M ${x1} ${y1} V ${busY} H ${x2} V ${y2}" class="connector${dashed ? ' dashed' : ''}"/>`;
}

